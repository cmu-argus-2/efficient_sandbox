static int8_t ov5642_bus_ok(const ov5642_t *dev)
{
    if ((dev == NULL) || (dev->bus.read_reg == NULL) || (dev->bus.write_reg == NULL)) {
        return OV5642_ERR_ARG;
    }
    return OV5642_OK;
}

int8_t ov5642_init(ov5642_t *dev, const ov5642_bus_t *bus)
{
    if ((dev == NULL) || (bus == NULL) ||
        (bus->read_reg == NULL) || (bus->write_reg == NULL)) {
        return OV5642_ERR_ARG;
    }

    dev->bus = *bus;
    return OV5642_OK;
}

static void ov5642_delay_ms(const ov5642_t *dev, uint32_t ms)
{
    if ((dev != NULL) && (dev->bus.delay_ms != NULL)) {
        dev->bus.delay_ms(dev->bus.ctx, ms);
    }
}

static int8_t ov5642_write_table(const ov5642_t *dev, const ov5642_reg8_t *table)
{
    size_t i = 0u;

    if ((ov5642_bus_ok(dev) != OV5642_OK) || (table == NULL)) {
        return OV5642_ERR_ARG;
    }

    while (!((table[i].reg == OV5642_REG_TERM) && (table[i].val == OV5642_VAL_TERM))) {
        if (ov5642_write_reg(dev, table[i].reg, table[i].val) != OV5642_OK) {
            return OV5642_ERR_IO;
        }
        ++i;
    }

    return OV5642_OK;
}

static const ov5642_reg8_t *ov5642_size_table(ov5642_jpeg_size_t size)
{
    switch (size) {
        case OV5642_SIZE_320X240:
            return ov5642_320x240;
        case OV5642_SIZE_640X480:
            return ov5642_640x480;
        case OV5642_SIZE_1024X768:
            return ov5642_1024x768;
        case OV5642_SIZE_1280X960:
            return ov5642_1280x960;
        case OV5642_SIZE_1600X1200:
            return ov5642_1600x1200;
        case OV5642_SIZE_2048X1536:
            return ov5642_2048x1536;
        case OV5642_SIZE_2592X1944:
            return ov5642_2592x1944;
        default:
            return NULL;
    }
}

int8_t ov5642_read_reg(const ov5642_t *dev, uint16_t reg, uint8_t *val)
{
    if ((ov5642_bus_ok(dev) != OV5642_OK) || (val == NULL)) {
        return OV5642_ERR_ARG;
    }

    return (dev->bus.read_reg(dev->bus.ctx, reg, val) == 0) ? OV5642_OK : OV5642_ERR_IO;
}

int8_t ov5642_write_reg(const ov5642_t *dev, uint16_t reg, uint8_t val)
{
    if (ov5642_bus_ok(dev) != OV5642_OK) {
        return OV5642_ERR_ARG;
    }

    return (dev->bus.write_reg(dev->bus.ctx, reg, val) == 0) ? OV5642_OK : OV5642_ERR_IO;
}

int8_t ov5642_read_id(const ov5642_t *dev, ov5642_id_t *id)
{
    if ((ov5642_bus_ok(dev) != OV5642_OK) || (id == NULL)) {
        return OV5642_ERR_ARG;
    }

    if (ov5642_read_reg(dev, OV5642_REG_CHIP_ID_HIGH, &id->chip_id_high) != OV5642_OK) {
        return OV5642_ERR_IO;
    }
    if (ov5642_read_reg(dev, OV5642_REG_CHIP_ID_LOW, &id->chip_id_low) != OV5642_OK) {
        return OV5642_ERR_IO;
    }

    return OV5642_OK;
}

int8_t ov5642_check_id(const ov5642_t *dev, ov5642_id_t *id)
{
    ov5642_id_t local_id;

    if (id == NULL) {
        id = &local_id;
    }

    if (ov5642_read_id(dev, id) != OV5642_OK) {
        return OV5642_ERR_IO;
    }

    if ((id->chip_id_high != OV5642_CHIP_ID_HIGH_VAL) ||
        (id->chip_id_low != OV5642_CHIP_ID_LOW_VAL)) {
        return OV5642_ERR_ID;
    }

    return OV5642_OK;
}

int8_t ov5642_set_jpeg_size(const ov5642_t *dev, ov5642_jpeg_size_t size)
{
    const ov5642_reg8_t *table = ov5642_size_table(size);

    if (table == NULL) {
        return OV5642_ERR_ARG;
    }

    return ov5642_write_table(dev, table);
}

int8_t ov5642_init_jpeg(const ov5642_t *dev, ov5642_jpeg_size_t size)
{
    if (ov5642_write_reg(dev, 0x3008u, 0x80u) != OV5642_OK) {
        return OV5642_ERR_IO;
    }

    if (ov5642_write_table(dev, ov5642_qvga_preview) != OV5642_OK) {
        return OV5642_ERR_IO;
    }
    ov5642_delay_ms(dev, 100u);

    if (ov5642_write_table(dev, ov5642_jpeg_capture_qsxga) != OV5642_OK) {
        return OV5642_ERR_IO;
    }

    if (ov5642_set_jpeg_size(dev, size) != OV5642_OK) {
        return OV5642_ERR_IO;
    }
    ov5642_delay_ms(dev, 100u);

    if (ov5642_write_reg(dev, 0x3818u, 0xA8u) != OV5642_OK) {
        return OV5642_ERR_IO;
    }
    if (ov5642_write_reg(dev, 0x3621u, 0x10u) != OV5642_OK) {
        return OV5642_ERR_IO;
    }
    if (ov5642_write_reg(dev, 0x3801u, 0xB0u) != OV5642_OK) {
        return OV5642_ERR_IO;
    }
    if (ov5642_write_reg(dev, 0x4407u, 0x08u) != OV5642_OK) {
        return OV5642_ERR_IO;
    }
    if (ov5642_write_reg(dev, 0x5888u, 0x00u) != OV5642_OK) {
        return OV5642_ERR_IO;
    }
    if (ov5642_write_reg(dev, 0x5000u, 0xFFu) != OV5642_OK) {
        return OV5642_ERR_IO;
    }

    return OV5642_OK;
}
